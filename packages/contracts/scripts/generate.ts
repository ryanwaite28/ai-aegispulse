// `make contracts` step 2: deterministic code generation from contracts (never hand-edit generated/).
// TS: envelope + event payloads (json-schema-to-typescript), OpenAPI (openapi-typescript), topology unions,
//     ServiceAction union (from internal OpenAPI operationIds + x-aegis-consumer-actions).
// Python: Pydantic v2 models for envelope + events (datamodel-code-generator via uv).
// Java: records for envelope + events and topology constants (scripts/java-records.ts), compiled by java-platform.
import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { compile } from "json-schema-to-typescript";
import openapiTS, { astToString } from "openapi-typescript";
import { parse as parseYaml } from "yaml";
import { contractsRoot, eventSchemaFiles, readJson, routingKeyOf } from "../src/schemas.js";
import { loadTopology } from "../src/topology.js";
import {
  eventTypesSource,
  exchangeNameSource,
  JavaRecordEmitter,
  queueNameSource,
  topologySource,
} from "./java-records.js";

const BANNER = "// GENERATED by packages/contracts/scripts/generate.ts — DO NOT EDIT. Source: packages/contracts.\n";
const out = join(contractsRoot, "generated");
const tsOut = join(out, "ts");
rmSync(out, { recursive: true, force: true });
mkdirSync(join(tsOut, "events"), { recursive: true });
mkdirSync(join(tsOut, "openapi"), { recursive: true });

const pascal = (s: string): string =>
  s
    .split(/[^a-zA-Z0-9]/)
    .filter(Boolean)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("");
const jsttOptions = {
  bannerComment: "",
  additionalProperties: false,
  strictIndexSignatures: true,
  format: true,
  cwd: join(contractsRoot, "events"),
};

// 1. Envelope
const envelopeSchema = readJson(join(contractsRoot, "envelope", "canonical-envelope.v1.schema.json")) as Record<
  string,
  unknown
>;
const envelopeTs = await compile(envelopeSchema as never, "CanonicalEnvelope", {
  ...jsttOptions,
  cwd: join(contractsRoot, "envelope"),
});
writeFileSync(join(tsOut, "envelope.ts"), BANNER + envelopeTs);

// 2. Event payloads
const keys = eventSchemaFiles()
  .filter((f) => !f.startsWith("_"))
  .map(routingKeyOf);
const indexLines: string[] = [BANNER, 'import type { CanonicalEnvelope } from "./envelope.js";'];
const mapLines: string[] = [];
for (const key of keys) {
  const typeName = `${pascal(key)}Payload`;
  const schema = readJson(join(contractsRoot, "events", `${key}.v1.schema.json`)) as Record<string, unknown>;
  const ts = await compile({ ...schema, title: typeName } as never, typeName, {
    ...jsttOptions,
    declareExternallyReferenced: true,
  });
  writeFileSync(join(tsOut, "events", `${key}.ts`), BANNER + ts);
  indexLines.push(`import type { ${typeName} } from "./events/${key}.js";`);
  mapLines.push(`  "${key}": ${typeName};`);
}
indexLines.push(
  "",
  "/** Routing key (= eventType) → payload type (PROJECT.md §6.7). */",
  "export interface EventPayloadMap {",
  ...mapLines,
  "}",
  "export type EventType = keyof EventPayloadMap;",
  'export type Envelope<K extends EventType> = Omit<CanonicalEnvelope, "eventType" | "payload"> & { eventType: K; payload: EventPayloadMap[K] };',
  `export const EVENT_TYPES = ${JSON.stringify(keys)} as const;`,
  "export type { CanonicalEnvelope };",
  "",
);
writeFileSync(join(tsOut, "events.ts"), indexLines.join("\n"));

// 3. Topology unions (typed generics for rxjs-rabbitmq in ts-platform/amqp)
const t = loadTopology();
const lit = (xs: string[]): string =>
  xs.length
    ? [...new Set(xs)]
        .sort()
        .map((x) => JSON.stringify(x))
        .join(" | ")
    : "never";
writeFileSync(
  join(tsOut, "topology.ts"),
  [
    BANNER,
    `export type ExchangeName = ${lit(t.exchanges.map((e) => e.name))};`,
    `export type QueueName = ${lit(t.queues.map((q) => q.name))};`,
    `export type WorkQueueName = ${lit(t.queues.filter((q) => q.role === undefined).map((q) => q.name))};`,
    `export type BindingKey = ${lit(t.bindings.map((b) => b.routingKey))};`,
    `export const QUEUE_PREFETCH: Readonly<Record<WorkQueueName, number>> = ${JSON.stringify(Object.fromEntries(t.queues.filter((q) => q.role === undefined).map((q) => [q.name, q.prefetch ?? 10])), null, 2)};`,
    `export const QUEUE_RETRY_TIERS: Readonly<Record<WorkQueueName, readonly string[]>> = ${JSON.stringify(Object.fromEntries(t.queues.filter((q) => q.role === undefined).map((q) => [q.name, q.retryTiers ?? []])), null, 2)};`,
    "",
  ].join("\n"),
);

// 4. OpenAPI types + ServiceAction union
const services: Array<[string, string]> = [
  ["registry", "registry"],
  ["ingestion", "ingestion"],
  ["files", "files"],
  ["events", "events"],
  ["cases", "cases"],
  ["risk-scoring", "riskScoring"],
  ["sensitivity-scanner", "scanner"],
  ["data-intel", "dataIntel"],
];
const saImports: string[] = [BANNER, 'import type { CanonicalEnvelope } from "./envelope.js";'];
const saUnion: string[] = [];
const saCatalog: string[] = [];
interface Op {
  operationId?: string;
  requestBody?: { content?: Record<string, { schema?: { $ref?: string } }> };
}
for (const [file, svc] of services) {
  const p = join(contractsRoot, "openapi", `${file}.internal.yaml`);
  if (!existsSync(p)) continue;
  const ast = await openapiTS(pathToFileURL(p), { alphabetize: true, exportType: true });
  writeFileSync(join(tsOut, "openapi", `${file}.ts`), BANNER + astToString(ast));
  const alias = `${pascal(file)}Api`;
  saImports.push(`import type { components as ${alias} } from "./openapi/${file}.js";`);
  const doc = parseYaml(readFileSync(p, "utf8")) as {
    paths?: Record<string, Record<string, Op>>;
    "x-aegis-consumer-actions"?: string[];
  };
  for (const [path, ops] of Object.entries(doc.paths ?? {})) {
    for (const [method, op] of Object.entries(ops)) {
      if (op.operationId === undefined) continue;
      const ref = op.requestBody?.content?.["application/json"]?.schema?.$ref;
      const schemaName = ref?.startsWith("#/components/schemas/")
        ? ref.slice("#/components/schemas/".length)
        : undefined;
      const payload =
        schemaName !== undefined ? `${alias}["schemas"][${JSON.stringify(schemaName)}]` : "Record<string, never>";
      saUnion.push(`  | { service: "${svc}"; action: "${op.operationId}"; payload: ${payload} }`);
      saCatalog.push(
        `  { service: "${svc}", action: "${op.operationId}", transport: "http", method: "${method.toUpperCase()}", path: "${path}" },`,
      );
    }
  }
  for (const a of doc["x-aegis-consumer-actions"] ?? []) {
    saUnion.push(`  | { service: "${svc}"; action: "${a}"; payload: { envelope: CanonicalEnvelope } }`);
    saCatalog.push(`  { service: "${svc}", action: "${a}", transport: "consumer" },`);
  }
}
for (const [svc, actions] of [
  [
    "orchestrator",
    [
      "scoreTransactionSaga",
      "classifiedSignalSaga",
      "caseCorrelationSaga",
      "extractionReviewSaga",
      "dispatchNotification",
    ],
  ],
  ["docExtraction", ["processFile"]],
] as const) {
  for (const a of actions) {
    saUnion.push(`  | { service: "${svc}"; action: "${a}"; payload: { envelope: CanonicalEnvelope } }`);
    saCatalog.push(`  { service: "${svc}", action: "${a}", transport: "consumer" },`);
  }
}
writeFileSync(
  join(tsOut, "service-actions.ts"),
  [
    ...saImports,
    "",
    "/** Every internal operation (PROJECT.md §6.2). Invoked by dispatch adapters; implemented only by service-layer modules. */",
    "export type ServiceAction =",
    ...saUnion,
    "  ;",
    'export type ServiceName = ServiceAction["service"];',
    'export type ActionName<S extends ServiceName> = Extract<ServiceAction, { service: S }>["action"];',
    'export type ActionPayload<S extends ServiceName, A extends ActionName<S>> = Extract<ServiceAction, { service: S; action: A }>["payload"];',
    "",
    "export const SERVICE_ACTIONS = [",
    ...saCatalog,
    "] as const;",
    "",
  ].join("\n"),
);

// 5. Python (Pydantic v2) for envelope + events
const pyOut = join(out, "python", "aegis_contracts");
const stage = mkdtempSync(join(tmpdir(), "aegis-contracts-"));
try {
  cpSync(join(contractsRoot, "envelope"), join(stage, "envelope"), {
    recursive: true,
    filter: (s) => !s.includes("examples"),
  });
  cpSync(join(contractsRoot, "events"), join(stage, "events"), {
    recursive: true,
    filter: (s) => !s.includes("examples"),
  });
  execFileSync(
    "uv",
    [
      "run",
      "--project",
      join(contractsRoot, "..", ".."),
      "datamodel-codegen",
      "--input",
      stage,
      "--input-file-type",
      "jsonschema",
      "--output",
      pyOut,
      "--output-model-type",
      "pydantic_v2.BaseModel",
      "--target-python-version",
      "3.13",
      "--use-standard-collections",
      "--use-union-operator",
      "--field-constraints",
      "--disable-timestamp",
      "--use-title-as-name",
      "--custom-file-header",
      "# GENERATED by packages/contracts/scripts/generate.ts — DO NOT EDIT.",
    ],
    { stdio: "inherit" },
  );
} finally {
  rmSync(stage, { recursive: true, force: true });
}
// 5b. Python packaging extras: schemas as package resources + topology StrEnums (wire names appear once)
const pyResources = join(pyOut, "resources");
mkdirSync(pyResources, { recursive: true });
cpSync(
  join(contractsRoot, "envelope", "canonical-envelope.v1.schema.json"),
  join(pyResources, "canonical-envelope.v1.schema.json"),
);
cpSync(join(contractsRoot, "topology", "aegispulse.topology.json"), join(pyResources, "aegispulse.topology.json"));
writeFileSync(
  join(pyResources, "__init__.py"),
  "# GENERATED by packages/contracts/scripts/generate.ts — DO NOT EDIT.\n",
);
const pyConst = (wire: string): string => wire.toUpperCase().replace(/[^A-Z0-9]+/g, "_");
const pyWork = t.queues.filter((q) => q.role === undefined).sort((a, b) => a.name.localeCompare(b.name));
writeFileSync(
  join(pyOut, "topology.py"),
  [
    "# GENERATED by packages/contracts/scripts/generate.ts — DO NOT EDIT.",
    '"""RabbitMQ topology contract (PROJECT.md §5.5, §6.5): names, prefetch, retry tiers and DLQ presence."""',
    "",
    "from dataclasses import dataclass",
    "from enum import StrEnum",
    "",
    "",
    "class QueueName(StrEnum):",
    '    """Every queue in the topology contract."""',
    "",
    ...[...t.queues.map((q) => q.name)].sort().map((n) => `    ${pyConst(n)} = ${JSON.stringify(n)}`),
    "",
    "",
    "class ExchangeName(StrEnum):",
    '    """Every exchange in the topology contract."""',
    "",
    ...[...t.exchanges.map((e) => e.name)].sort().map((n) => `    ${pyConst(n)} = ${JSON.stringify(n)}`),
    "",
    "",
    "@dataclass(frozen=True, slots=True)",
    "class QueuePolicy:",
    '    """Consumer policy for one work queue."""',
    "",
    "    queue: QueueName",
    "    prefetch: int",
    "    retry_tiers: tuple[str, ...]",
    "    dead_letter: bool",
    "",
    "",
    "RETRY_EXCHANGE = ExchangeName.AEGISPULSE_RETRY",
    "DEAD_LETTER_EXCHANGE = ExchangeName.AEGISPULSE_DLX",
    "",
    "WORK_QUEUES: dict[QueueName, QueuePolicy] = {",
    ...pyWork.map((q) => {
      const c = `QueueName.${pyConst(q.name)}`;
      const tiers = (q.retryTiers ?? []).map((x) => JSON.stringify(x));
      const tuple = tiers.length === 0 ? "()" : `(${tiers.join(", ")}${tiers.length === 1 ? "," : ""})`;
      return `    ${c}: QueuePolicy(${c}, ${q.prefetch ?? 10}, ${tuple}, ${typeof q.deadLetterQueue === "string" && q.deadLetterQueue !== "" ? "True" : "False"}),`;
    }),
    "}",
    "",
    "",
    "def policy(queue: QueueName) -> QueuePolicy:",
    '    """Policy for a work queue; raises KeyError for retry/DLQ/delay queues."""',
    "    try:",
    "        return WORK_QUEUES[queue]",
    "    except KeyError:",
    '        raise KeyError(f"not a work queue: {queue}") from None',
    "",
  ].join("\n"),
);
writeFileSync(join(pyOut, "py.typed"), "");

// 6. Java records (envelope + events) and topology constants
const java = new JavaRecordEmitter(contractsRoot);
java.emitRoot("envelope/canonical-envelope.v1.schema.json", "CanonicalEnvelope");
const javaEvents: Array<[string, string]> = keys.map((key) => [
  key,
  java.emitRoot(`events/${key}.v1.schema.json`, `${pascal(key)}Payload`),
]);
java.emitRaw("io.aegispulse.contracts.events", "EventTypes", eventTypesSource(javaEvents));
java.emitRaw("io.aegispulse.contracts.topology", "QueueName", queueNameSource(t));
java.emitRaw("io.aegispulse.contracts.topology", "ExchangeName", exchangeNameSource(t));
java.emitRaw("io.aegispulse.contracts.topology", "Topology", topologySource(t));
const javaCount = java.write(join(out, "java"));

process.stdout.write(
  `generate: ${keys.length} event types, ${saCatalog.length} service actions, topology unions, python models, ${javaCount} java types\n`,
);
