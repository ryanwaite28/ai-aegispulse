// JSON Schema → Java records (PROJECT.md §11 Phase 1 "Java records"; used by java-platform and the Java services).
// Deterministic and dependency-free: plain records plus JSpecify @Nullable (no Jackson annotations, so the wire
// names equal the record component names, snake_case lineage fields included). Validation stays in JSON Schema
// (the platform validates envelopes before binding); records only give typed access.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, posix } from "node:path";
import { readJson } from "../src/schemas.js";
import type { Topology } from "../src/topology.js";

type Schema = Record<string, unknown>;

const JAVA_BANNER =
  "// GENERATED by packages/contracts/scripts/generate.ts — DO NOT EDIT. Source: packages/contracts.\n";
const BASE_PACKAGE = "io.aegispulse.contracts";
const ENUM_CONSTANT = /^[A-Z][A-Z0-9_]*$/;

const pascal = (s: string): string =>
  s
    .split(/[^a-zA-Z0-9]/)
    .filter(Boolean)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("");

/** Places a type-use annotation where Java allows it on a qualified type: java.util.@Nullable List<String>. */
const annotateType = (type: string, annotation: string): string => {
  const generic = type.indexOf("<");
  const head = generic === -1 ? type : type.slice(0, generic);
  const dot = head.lastIndexOf(".");
  return dot === -1 ? `${annotation} ${type}` : `${type.slice(0, dot + 1)}${annotation} ${type.slice(dot + 1)}`;
};

const javadoc = (text: unknown, indent: string): string[] => {
  if (typeof text !== "string" || text.trim() === "") return [];
  const safe = text
    .replaceAll("*/", "*&#47;")
    .replaceAll("@", "{@literal @}")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");
  return [`${indent}/** ${safe.replaceAll("\n", " ")} */`];
};

interface Located {
  readonly schema: Schema;
  /** Contracts-relative file path, e.g. "events/_shared.v1.schema.json". */
  readonly file: string;
  /** Pointer inside that file ("" = root). */
  readonly pointer: string;
}

/** A top-level Java type emitted to its own file. */
interface NamedType {
  readonly pkg: string;
  readonly name: string;
  readonly source: string;
}

export class JavaRecordEmitter {
  private readonly docs = new Map<string, Schema>();
  /** "file#pointer" of a $defs entry → fully qualified Java type (records/enums emitted once). */
  private readonly defTypes = new Map<string, string>();
  private readonly emitted: NamedType[] = [];

  constructor(private readonly contractsRoot: string) {}

  private doc(file: string): Schema {
    let d = this.docs.get(file);
    if (d === undefined) {
      d = readJson(join(this.contractsRoot, file)) as Schema;
      this.docs.set(file, d);
    }
    return d;
  }

  private resolve(ref: string, from: Located): Located {
    const [path, fragment = ""] = ref.split("#");
    const file =
      path === undefined || path === "" ? from.file : posix.normalize(posix.join(posix.dirname(from.file), path));
    let node: unknown = this.doc(file);
    const parts = fragment.split("/").filter(Boolean);
    for (const p of parts) {
      node = (node as Schema)[p.replaceAll("~1", "/").replaceAll("~0", "~")];
      if (node === undefined) throw new Error(`unresolvable $ref ${ref} from ${from.file}`);
    }
    return { schema: node as Schema, file, pointer: fragment };
  }

  /** Package for types defined in a contracts file. */
  private packageOf(file: string): string {
    return file.startsWith("envelope/") ? `${BASE_PACKAGE}.envelope` : `${BASE_PACKAGE}.events`;
  }

  /** Flattens allOf/$ref into one object view (properties + required). */
  private objectView(loc: Located): {
    properties: Array<[string, Located]>;
    required: Set<string>;
    description: unknown;
  } {
    const properties = new Map<string, Located>();
    const required = new Set<string>();
    const visit = (l: Located): void => {
      const s = l.schema;
      if (typeof s["$ref"] === "string") visit(this.resolve(s["$ref"], l));
      for (const [i, part] of ((s["allOf"] as Schema[] | undefined) ?? []).entries()) {
        visit({ schema: part, file: l.file, pointer: `${l.pointer}/allOf/${i}` });
      }
      for (const [name, prop] of Object.entries(
        (s["properties"] as Record<string, Schema | boolean> | undefined) ?? {},
      )) {
        if (typeof prop === "boolean") continue;
        properties.set(name, { schema: prop, file: l.file, pointer: `${l.pointer}/properties/${name}` });
      }
      for (const r of (s["required"] as string[] | undefined) ?? []) required.add(r);
    };
    visit(loc);
    return {
      properties: [...properties.entries()].sort(([a], [b]) => a.localeCompare(b)),
      required,
      description: loc.schema["description"],
    };
  }

  private isObjectSchema(s: Schema): boolean {
    return s["type"] === "object" && (s["properties"] !== undefined || s["allOf"] !== undefined);
  }

  /** Java type for a property schema. `nested` collects inline records/enums declared inside the parent record. */
  private typeOf(loc: Located, hint: string, nested: string[], indent: string): { type: string; nullable: boolean } {
    const s = loc.schema;
    if (typeof s["$ref"] === "string" && Object.keys(s).filter((k) => k !== "description").length === 1) {
      const target = this.resolve(s["$ref"], loc);
      const key = `${target.file}#${target.pointer}`;
      const isDef = /^\/\$defs\/[^/]+$/.test(target.pointer);
      if (isDef) {
        const named = this.namedDef(target, key);
        if (named !== undefined) return { type: named, nullable: false };
      }
      return this.typeOf(target, hint, nested, indent);
    }
    const allOf = s["allOf"] as Schema[] | undefined;
    if (allOf?.length === 1 && s["properties"] === undefined && allOf[0] !== undefined) {
      return this.typeOf({ schema: allOf[0], file: loc.file, pointer: `${loc.pointer}/allOf/0` }, hint, nested, indent);
    }
    for (const key of ["anyOf", "oneOf"] as const) {
      const alts = s[key] as Schema[] | undefined;
      if (alts !== undefined && s["properties"] === undefined) {
        const nonNull = alts.filter((a) => a["type"] !== "null");
        const nullable = nonNull.length < alts.length;
        if (nonNull.length === 1 && nonNull[0] !== undefined) {
          const inner = this.typeOf(
            { schema: nonNull[0], file: loc.file, pointer: `${loc.pointer}/${key}/0` },
            hint,
            nested,
            indent,
          );
          return { type: inner.type, nullable: nullable || inner.nullable };
        }
        return { type: "Object", nullable };
      }
    }
    const type = s["type"];
    if (Array.isArray(type)) {
      const nonNull = type.filter((t) => t !== "null");
      const nullable = nonNull.length < type.length;
      if (nonNull.length === 1)
        return {
          type: this.typeOf({ ...loc, schema: { ...s, type: nonNull[0] } }, hint, nested, indent).type,
          nullable,
        };
      return { type: "Object", nullable };
    }
    switch (type) {
      case "string": {
        const values = s["enum"] as unknown[] | undefined;
        if (values !== undefined && values.every((v) => typeof v === "string" && ENUM_CONSTANT.test(v))) {
          nested.push(...this.enumSource(pascal(hint), values as string[], s["description"], indent));
          return { type: pascal(hint), nullable: false };
        }
        if (s["format"] === "date-time") return { type: "java.time.OffsetDateTime", nullable: false };
        if (s["format"] === "uuid") return { type: "java.util.UUID", nullable: false };
        if (s["format"] === "uri") return { type: "java.net.URI", nullable: false };
        return { type: "String", nullable: false };
      }
      case "integer":
        return { type: "Long", nullable: false };
      case "number":
        return { type: "java.math.BigDecimal", nullable: false };
      case "boolean":
        return { type: "Boolean", nullable: false };
      case "array": {
        const items = s["items"] as Schema | undefined;
        if (items === undefined) return { type: "java.util.List<Object>", nullable: false };
        const inner = this.typeOf(
          { schema: items, file: loc.file, pointer: `${loc.pointer}/items` },
          `${hint}Item`,
          nested,
          indent,
        );
        return { type: `java.util.List<${inner.type}>`, nullable: false };
      }
      case "object":
        if (this.isObjectSchema(s)) {
          nested.push(...this.recordSource(pascal(hint), loc, indent));
          return { type: pascal(hint), nullable: false };
        }
        return { type: "java.util.Map<String, @Nullable Object>", nullable: false };
      default:
        if (s["enum"] !== undefined || s["const"] !== undefined) return { type: "String", nullable: false };
        return { type: "Object", nullable: false };
    }
  }

  /** Emits a $defs entry as its own top-level type when it is a record or a constant enum; else undefined. */
  private namedDef(target: Located, key: string): string | undefined {
    const existing = this.defTypes.get(key);
    if (existing !== undefined) return existing;
    const s = target.schema;
    const name = pascal(target.pointer.split("/").at(-1) ?? "Def");
    const pkg = this.packageOf(target.file);
    const fqn = `${pkg}.${name}`;
    const values = s["enum"] as unknown[] | undefined;
    if (
      s["type"] === "string" &&
      values !== undefined &&
      values.every((v) => typeof v === "string" && ENUM_CONSTANT.test(v))
    ) {
      this.defTypes.set(key, fqn);
      this.emitted.push({
        pkg,
        name,
        source: this.enumSource(name, values as string[], s["description"], "").join("\n"),
      });
      return fqn;
    }
    if (this.isObjectSchema(s)) {
      this.defTypes.set(key, fqn);
      this.emitted.push({ pkg, name, source: this.recordSource(name, target, "").join("\n") });
      return fqn;
    }
    return undefined;
  }

  private enumSource(name: string, values: string[], description: unknown, indent: string): string[] {
    return [
      ...javadoc(description, indent),
      `${indent}public enum ${name} {`,
      `${indent}  ${values.join(",\n" + indent + "  ")}`,
      `${indent}}`,
    ];
  }

  private recordSource(name: string, loc: Located, indent: string): string[] {
    const view = this.objectView(loc);
    const nested: string[] = [];
    const components = view.properties.map(([prop, ploc]) => {
      const t = this.typeOf(ploc, prop, nested, `${indent}  `);
      const nullable = t.nullable || !view.required.has(prop);
      const doc = ploc.schema["description"];
      const comment = typeof doc === "string" ? ` // ${doc.replaceAll("\n", " ").slice(0, 160)}` : "";
      return { line: `${indent}    ${nullable ? annotateType(t.type, "@Nullable") : t.type} ${prop}`, comment };
    });
    const lines = [
      ...javadoc(view.description, indent),
      `${indent}public record ${name}(`,
      ...components.map((c, i) => `${c.line}${i < components.length - 1 ? "," : ""}${c.comment}`),
      `${indent}) {`,
      ...nested,
      `${indent}}`,
    ];
    return lines;
  }

  /** Emits the root schema of `file` as record `name` in `pkg`. */
  emitRoot(file: string, name: string): string {
    const schema = this.doc(file);
    const pkg = this.packageOf(file);
    this.emitted.push({ pkg, name, source: this.recordSource(name, { schema, file, pointer: "" }, "").join("\n") });
    return `${pkg}.${name}`;
  }

  emitRaw(pkg: string, name: string, source: string): void {
    this.emitted.push({ pkg, name, source });
  }

  write(outDir: string): number {
    const byName = new Map<string, NamedType>();
    for (const t of this.emitted) {
      const key = `${t.pkg}.${t.name}`;
      if (byName.has(key)) throw new Error(`duplicate Java type ${key}`);
      byName.set(key, t);
    }
    for (const t of [...byName.values()].sort((a, b) => `${a.pkg}.${a.name}`.localeCompare(`${b.pkg}.${b.name}`))) {
      const path = join(outDir, ...t.pkg.split("."), `${t.name}.java`);
      mkdirSync(dirname(path), { recursive: true });
      const usesNullable = t.source.includes("@Nullable");
      writeFileSync(
        path,
        `${JAVA_BANNER}package ${t.pkg};\n\n${usesNullable ? "import org.jspecify.annotations.Nullable;\n\n" : ""}${t.source}\n`,
      );
    }
    return byName.size;
  }
}

const javaString = (s: string): string => JSON.stringify(s);

/** Upper-snake Java constant for a wire name: "cases.audit-ingest.q.retry.1s" → CASES_AUDIT_INGEST_Q_RETRY_1S. */
const constantName = (wire: string): string => wire.toUpperCase().replace(/[^A-Z0-9]+/g, "_");

/** A wire-name enum: one constant per name, the literal appears exactly once. */
function wireEnumSource(name: string, doc: string, wires: string[]): string {
  const sorted = [...new Set(wires)].sort();
  const constants = sorted.map((w) => `  ${constantName(w)}(${javaString(w)})`);
  return [
    `/** ${doc} */`,
    `public enum ${name} {`,
    `${constants.join(",\n")};`,
    "",
    "  private final String wireName;",
    "",
    `  ${name}(String wireName) {`,
    "    this.wireName = wireName;",
    "  }",
    "",
    "  /** The name on the broker. */",
    "  public String wireName() {",
    "    return wireName;",
    "  }",
    "",
    `  private static final java.util.Map<String, ${name}> BY_WIRE_NAME =`,
    `      java.util.Arrays.stream(values()).collect(java.util.stream.Collectors.toUnmodifiableMap(${name}::wireName, v -> v));`,
    "",
    "  /** Looks up a broker name; throws IllegalArgumentException for names outside the contract. */",
    `  public static ${name} fromWireName(String wireName) {`,
    `    ${name} value = BY_WIRE_NAME.get(wireName);`,
    "    if (value == null) {",
    `      throw new IllegalArgumentException("not in the topology contract: " + wireName);`,
    "    }",
    "    return value;",
    "  }",
    "}",
  ].join("\n");
}

export function queueNameSource(t: Topology): string {
  return wireEnumSource(
    "QueueName",
    "Every queue in the RabbitMQ topology contract (PROJECT.md §5.5).",
    t.queues.map((q) => q.name),
  );
}

export function exchangeNameSource(t: Topology): string {
  return wireEnumSource(
    "ExchangeName",
    "Every exchange in the RabbitMQ topology contract (PROJECT.md §6.5).",
    t.exchanges.map((e) => e.name),
  );
}

/** Topology policy keyed by the QueueName enum (the Java counterpart of generated/ts/topology.ts). */
export function topologySource(t: Topology): string {
  const work = t.queues.filter((q) => q.role === undefined).sort((a, b) => a.name.localeCompare(b.name));
  return [
    "/** RabbitMQ topology contract (PROJECT.md §5.5, §6.5): prefetch, retry tiers and DLQ presence per work queue. */",
    "public final class Topology {",
    "  private Topology() {}",
    "",
    "  /** Consumer policy for one work queue. */",
    "  public record QueuePolicy(QueueName queue, int prefetch, java.util.List<String> retryTiers, boolean deadLetter) {}",
    "",
    "  public static final ExchangeName RETRY_EXCHANGE = ExchangeName.AEGISPULSE_RETRY;",
    "  public static final ExchangeName DEAD_LETTER_EXCHANGE = ExchangeName.AEGISPULSE_DLX;",
    "",
    "  public static final java.util.Map<QueueName, QueuePolicy> WORK_QUEUES = java.util.Map.ofEntries(",
    work
      .map((q) => {
        const c = `QueueName.${constantName(q.name)}`;
        return `      java.util.Map.entry(${c}, new QueuePolicy(${c}, ${q.prefetch ?? 10}, java.util.List.of(${(q.retryTiers ?? []).map(javaString).join(", ")}), ${typeof q.deadLetterQueue === "string" && q.deadLetterQueue !== ""}))`;
      })
      .join(",\n"),
    "  );",
    "",
    "  /** Policy for a work queue; throws IllegalArgumentException for retry/DLQ/delay queues. */",
    "  public static QueuePolicy policy(QueueName queue) {",
    "    QueuePolicy policy = WORK_QUEUES.get(queue);",
    "    if (policy == null) {",
    '      throw new IllegalArgumentException("not a work queue: " + queue.wireName());',
    "    }",
    "    return policy;",
    "  }",
    "}",
  ].join("\n");
}

/** Event type → payload record class registry. */
export function eventTypesSource(entries: Array<[string, string]>): string {
  return [
    "/** Routing key (= eventType) → payload record (PROJECT.md §6.7). */",
    "public final class EventTypes {",
    "  private EventTypes() {}",
    "",
    "  public static final java.util.Map<String, Class<? extends Record>> PAYLOADS = java.util.Map.ofEntries(",
    entries.map(([key, cls]) => `      java.util.Map.entry(${javaString(key)}, ${cls}.class)`).join(",\n"),
    "  );",
    "}",
  ].join("\n");
}
