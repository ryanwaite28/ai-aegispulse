#!/usr/bin/env bash
# Generates a local-only .env with random secrets for the compose stack (PROJECT.md §10.2, §10.4).
# Never used for dev/prod (those come from Infisical). Refuses to overwrite an existing .env unless --force.
set -euo pipefail
root="$(cd "$(dirname "$0")/../.." && pwd)"
out="$root/.env"
if [[ -f "$out" && "${1:-}" != "--force" ]]; then
  echo "gen-local-secrets: $out exists (use --force to regenerate; this invalidates existing local volumes)" >&2
  exit 0
fi
hex() { openssl rand -hex "${1:-24}"; }
{
  echo "# Generated by scripts/dev/gen-local-secrets.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). LOCAL ONLY. Never commit."
  sed -n '/^# ---- BEGIN GENERATED ----$/,/^# ---- END GENERATED ----$/p' "$root/.env.example" | while IFS= read -r line; do
    if [[ "$line" =~ ^([A-Z0-9_]+)=\<generated(:([0-9a-z]+))?\>(.*)$ ]]; then
      name="${BASH_REMATCH[1]}"; spec="${BASH_REMATCH[3]:-24}"
      if [[ "$name" == "MONGO_KEYFILE" ]]; then val="$(openssl rand -base64 756 | tr -d '\n')"
      elif [[ "$spec" == "strong" ]]; then val="Aa1-$(hex 20)"   # tools requiring mixed case + digit + symbol
      else val="$(hex "$spec")"; fi
      echo "${name}=${val}"
    else
      echo "$line"
    fi
  done
  sed -n '/^# ---- END GENERATED ----$/,$p' "$root/.env.example" | tail -n +2
} > "$out"
chmod 600 "$out"
# Derive the local OTLP header (OpenObserve basic auth) from the generated root password, so traces/metrics from the
# compose runtimes are accepted (NFR-07). OTel env headers are percent-encoded: "Authorization=Basic%20<b64>".
o2_pw="$(sed -n 's/^OPENOBSERVE_LOCAL_PASSWORD=//p' "$out")"
if [[ -n "$o2_pw" ]]; then
  header="Authorization=Basic%20$(printf 'dev@aegispulse.local:%s' "$o2_pw" | base64 | tr -d '\n')"
  tmp="$(mktemp)"
  grep -v '^OTEL_EXPORTER_OTLP_HEADERS=' "$out" > "$tmp" || true
  echo "OTEL_EXPORTER_OTLP_HEADERS=${header}" >> "$tmp"
  mv "$tmp" "$out"
  chmod 600 "$out"
fi
echo "gen-local-secrets: wrote $out"
